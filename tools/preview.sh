#!/usr/bin/env bash
set -euo pipefail

usage() {
    cat <<'USAGE'
Usage: tools/preview.sh [--checkout PATH] [--port PORT] [--keep-profile] [--no-seed-library]

Launch the local KOReader Bookshelf noVNC preview after applying and validating
the plugin mirror.

Options:
  --checkout PATH      KOReader checkout path. Defaults to $KOREADER_CHECKOUT,
                       then ../koreader.
  --port PORT          Host port for noVNC. Defaults to $BOOKSHELF_PREVIEW_PORT,
                       then 6081.
  --keep-profile       Reuse .tmp/preview-home/default instead of resetting it.
  --no-seed-library    Skip KOReader's sample-library seeding helper.
  -h, --help           Show this help.
USAGE
}

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/.." && pwd)"

checkout="${KOREADER_CHECKOUT:-}"
port="${BOOKSHELF_PREVIEW_PORT:-6081}"
reset_profile=1
seed_library=1

while [[ $# -gt 0 ]]; do
    case "$1" in
        --checkout)
            if [[ $# -lt 2 ]]; then
                echo "preview failed: --checkout requires a path" >&2
                exit 64
            fi
            checkout="$2"
            shift 2
            ;;
        --port)
            if [[ $# -lt 2 ]]; then
                echo "preview failed: --port requires a value" >&2
                exit 64
            fi
            port="$2"
            shift 2
            ;;
        --keep-profile)
            reset_profile=0
            shift
            ;;
        --no-seed-library)
            seed_library=0
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "preview failed: unknown argument $1" >&2
            usage >&2
            exit 64
            ;;
    esac
done

if [[ -z "${checkout}" ]]; then
    checkout="${repo_root}/../koreader"
fi

if ! checkout="$(cd "${checkout}" 2>/dev/null && pwd)"; then
    echo "preview failed: KOReader checkout does not exist: ${checkout}" >&2
    exit 2
fi

if [[ ! -f "${checkout}/reader.lua" || ! -d "${checkout}/frontend" || ! -d "${checkout}/plugins" ]]; then
    echo "preview failed: not a KOReader checkout: ${checkout}" >&2
    exit 2
fi

if ! [[ "${port}" =~ ^[0-9]+$ ]]; then
    echo "preview failed: --port must be numeric: ${port}" >&2
    exit 64
fi

compose_bin=()
if docker compose version >/dev/null 2>&1; then
    compose_bin=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
    compose_bin=(docker-compose)
else
    echo "preview failed: docker compose is not available" >&2
    exit 69
fi

export KOREADER_CHECKOUT="${checkout}"
export BOOKSHELF_REPO="${repo_root}"
export BOOKSHELF_PREVIEW_PORT="${port}"
export BOOKSHELF_PREVIEW_HOME="${BOOKSHELF_PREVIEW_HOME:-${repo_root}/.tmp/preview-home/default}"
export EMULATE_READER_W="${EMULATE_READER_W:-1404}"
export EMULATE_READER_H="${EMULATE_READER_H:-1872}"
export EMULATE_READER_DPI="${EMULATE_READER_DPI:-226}"

python3 "${repo_root}/tools/apply_to_koreader_checkout.py" --checkout "${KOREADER_CHECKOUT}"
python3 "${repo_root}/tools/validate_bookshelf_manifest.py" --strict --checkout "${KOREADER_CHECKOUT}"

library_dir="${KOREADER_CHECKOUT}/.tmp/bookshelf-sample-library"
if [[ "${seed_library}" -eq 1 && -f "${KOREADER_CHECKOUT}/tools/bookshelf_seed_sample_library.py" ]]; then
    python3 "${KOREADER_CHECKOUT}/tools/bookshelf_seed_sample_library.py" \
        --library "${library_dir}" \
        --runtime-library "/work/.tmp/bookshelf-sample-library" \
        --settings "${BOOKSHELF_PREVIEW_HOME}/settings.reader.lua" \
        --no-settings
fi

if [[ -d "${library_dir}" ]]; then
    python3 - "${library_dir}" <<'PY'
