import sys
import time
from pathlib import Path

library = Path(sys.argv[1])
showcase_order = [
    "01-alice-adventures-in-wonderland.epub",
    "02-frankenstein.epub",
    "03-dracula.epub",
    "04-the-time-machine.epub",
    "05-the-war-of-the-worlds.epub",
    "06-the-picture-of-dorian-gray.epub",
    "07-adventures-of-sherlock-holmes.epub",
    "08-moby-dick.epub",
    "09-the-yellow-wallpaper.epub",
]
now = int(time.time())
for offset, filename in enumerate(showcase_order):
    path = library / filename
    if path.exists():
        timestamp = now - offset * 60
        os.utime(path, (timestamp, timestamp))
PY
fi

if [[ "${reset_profile}" -eq 1 ]]; then
    rm -rf "${BOOKSHELF_PREVIEW_HOME}"
fi
mkdir -p "${BOOKSHELF_PREVIEW_HOME}/screenshots"
if [[ -d "${repo_root}/assets/fonts" ]]; then
    mkdir -p "${BOOKSHELF_PREVIEW_HOME}/.local/share/fonts/bookshelf"
    cp -R "${repo_root}/assets/fonts/." "${BOOKSHELF_PREVIEW_HOME}/.local/share/fonts/bookshelf/"
fi

if [[ ! -f "${BOOKSHELF_PREVIEW_HOME}/settings.reader.lua" ]]; then
    cat > "${BOOKSHELF_PREVIEW_HOME}/settings.reader.lua" <<SETTINGS
-- Generated by koreader-bookshelf/tools/preview.sh.
return {
    ["auto_standby_timeout_seconds"] = -1,
    ["auto_suspend_timeout_seconds"] = -1,
    ["bookshelf_auto_apply_reading_preset"] = "literary-latin",
    ["color_rendering"] = false,
    ["download_dir"] = "/work/.tmp/bookshelf-sample-library",
    ["footer"] = {
        ["align"] = "center",
        ["all_at_once"] = false,
        ["auto_refresh_time"] = false,
        ["battery"] = false,
        ["battery_hide_threshold"] = 100,
        ["book_author"] = false,
        ["book_author_max_width_pct"] = 30,
        ["book_chapter"] = false,
        ["book_chapter_max_width_pct"] = 30,
        ["book_time_to_read"] = false,
        ["book_title"] = false,
        ["book_title_max_width_pct"] = 30,
        ["bookmark_count"] = false,
        ["bottom_horizontal_separator"] = true,
        ["chapter_progress"] = false,
        ["chapter_progress_bar"] = false,
        ["chapter_time_to_read"] = false,
        ["container_bottom_padding"] = 1,
        ["container_height"] = 14,
        ["disable_progress_bar"] = false,
        ["disabled"] = false,
        ["footer_layout"] = "three_zone",
        ["frontlight"] = false,
        ["hide_empty_generators"] = false,
        ["initial_marker"] = false,
        ["invert_progress_direction"] = false,
        ["item_prefix"] = "icons",
        ["items_separator"] = "bar",
        ["lock_tap"] = false,
        ["mem_usage"] = false,
        ["page_progress"] = true,
        ["page_turning_inverted"] = false,
        ["pages_left"] = true,
        ["pages_left_book"] = false,
        ["pages_left_includes_current_page"] = false,
        ["percentage"] = true,
        ["progress_bar_min_width_pct"] = 20,
        ["progress_bar_position"] = "alongside",
        ["progress_margin"] = false,
        ["progress_margin_width"] = 10,
        ["progress_pct_format"] = "0",
        ["progress_style_thick_height"] = 7,
        ["progress_style_thin"] = false,
        ["progress_style_thin_height"] = 3,
        ["reclaim_height"] = false,
        ["skim_widget_on_hold"] = false,
        ["text_font_bold"] = false,
        ["text_font_face"] = "./fonts/noto/NotoSans-Regular.ttf",
        ["text_font_size"] = 14,
        ["three_zone_footer_state"] = "pages_left",
        ["three_zone_min_gap"] = 32,
        ["three_zone_text_font_bold"] = true,
        ["three_zone_text_font_size"] = 10,
        ["time"] = false,
        ["toc_markers"] = true,
        ["toc_markers_width"] = 2,
        ["wifi_status"] = false,
    },
    ["home_dir"] = "/work/.tmp/bookshelf-sample-library",
    ["lastdir"] = "/work/.tmp/bookshelf-sample-library",
    ["plugins_disabled"] = {
        ["statistics"] = true,
    },
    ["quickstart_shown_version"] = 9999999999,
    ["screensaver_type"] = "disable",
    ["sdl_window"] = {
        ["height"] = ${EMULATE_READER_H},
        ["width"] = ${EMULATE_READER_W},
    },
    ["start_with"] = "library",
}
SETTINGS
fi

if [[ ! -f "${BOOKSHELF_PREVIEW_HOME}/history.lua" && -d "${library_dir}" ]]; then
    now="$(date +%s)"
    first="/work/.tmp/bookshelf-sample-library/01-alice-adventures-in-wonderland.epub"
    second="/work/.tmp/bookshelf-sample-library/02-frankenstein.epub"
    cat > "${BOOKSHELF_PREVIEW_HOME}/history.lua" <<HISTORY
-- Generated by koreader-bookshelf/tools/preview.sh.
return {
    [1] = { ["file"] = "${first}", ["time"] = ${now} },
    [2] = { ["file"] = "${second}", ["time"] = $((now - 60)) },
}
HISTORY
fi

docker rm -f \
    koreader-bookshelf-novnc-preview \
    koreader-bookshelf-novnc \
    koreader-bookshelf-dev-novnc \
    koreader-bookshelf-qa \
    >/dev/null 2>&1 || true

"${compose_bin[@]}" -f "${repo_root}/docker-compose.yml" up --build -d novnc-preview

echo
echo "Bookshelf preview ready:"
echo "  http://localhost:${BOOKSHELF_PREVIEW_PORT}/vnc.html?autoconnect=true&resize=scale"
echo
echo "Profile:"
echo "  ${BOOKSHELF_PREVIEW_HOME}"
echo
